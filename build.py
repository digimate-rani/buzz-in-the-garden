#!/usr/bin/env python3
"""Build the playable site (offline-ready PWA) from src/buzz.html.

Usage:  python3 build.py

Writes docs/index.html and docs/sw.js. docs/ is the whole site: GitHub Pages
serves it, and a server can host the same folder as-is. The service worker's cache name is a hash of
the files, so every rebuild with a change makes phones pick up the new version.
Standard library only.
"""
import hashlib
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "src" / "buzz.html"
PUBLIC = HERE / "docs"

FONTS = [
    ("fredoka-hebrew.woff2", "U+0307-0308, U+0590-05FF, U+200C-2010, U+20AA, U+25CC, U+FB1D-FB4F"),
    ("fredoka-latin-ext.woff2", "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C4, U+2113, U+2C60-2C7F, U+A720-A7FF"),
    ("fredoka-latin.woff2", "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD"),
]

HEAD = """<!doctype html>
<html lang="he" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#2f5e1e">
<meta name="description" content="דבורה אוספת אבקה בגינה, בונה רצפי צבעים ובורחת מצרעות. 10 שלבים, עובד גם בלי אינטרנט.">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="באזז">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" href="icons/favicon-64.png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
{title}
<style>
{fontfaces}
</style>
</head>
<body>
"""

REGISTER_SW = """
<script>
  // keep a copy of the game on the phone so it opens without internet
  if ('serviceWorker' in navigator) {
    window.addEventListener('load', () => { navigator.serviceWorker.register('./sw.js').catch(() => {}); });
  }
</script>
</body>
</html>
"""

SW = """// Generated by build.py. Do not edit by hand: change src/buzz.html and rebuild.
const CACHE = 'buzz-__VERSION__';
const ASSETS = __ASSETS__;

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k.startsWith('buzz-') && k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Offline first: answer from the saved copy, fall back to the network.
self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    event.respondWith(caches.match('./index.html').then(hit => hit || fetch(req)));
    return;
  }
  event.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req)));
});
"""


def main():
    src = SRC.read_text(encoding="utf-8")

    title_match = re.search(r"<title>.*?</title>", src)
    if not title_match:
        raise SystemExit("src/buzz.html has no <title>")
    body = src.replace(title_match.group(0), "", 1)

    # drop the Google Fonts links: the font ships with the app
    body = "\n".join(
        line for line in body.split("\n")
        if "fonts.googleapis.com" not in line and "fonts.gstatic.com" not in line
    ).lstrip("\n")

    fontfaces = "\n".join(
        "  @font-face { font-family: 'Fredoka'; font-style: normal; font-weight: 300 700; font-display: swap;\n"
        f"    src: url(fonts/{name}) format('woff2'); unicode-range: {rng}; }}"
        for name, rng in FONTS
    )

    html = HEAD.format(title=title_match.group(0), fontfaces=fontfaces) + body.rstrip() + "\n" + REGISTER_SW
    (PUBLIC / "index.html").write_text(html, encoding="utf-8")

    assets = ["./", "./index.html", "./manifest.webmanifest"]
    assets += [f"./fonts/{name}" for name, _ in FONTS]
    assets += sorted(f"./icons/{p.name}" for p in (PUBLIC / "icons").glob("*.png"))
    for a in assets[2:]:
        if not (PUBLIC / a[2:]).exists():
            raise SystemExit(f"missing file: docs/{a[2:]}")

    digest = hashlib.sha256()
    for a in assets[1:]:
        digest.update((PUBLIC / a[2:]).read_bytes())
    version = digest.hexdigest()[:10]

    assets_js = "[\n  " + ",\n  ".join(f"'{a}'" for a in assets) + "\n]"
    (PUBLIC / "sw.js").write_text(SW.replace("__VERSION__", version).replace("__ASSETS__", assets_js), encoding="utf-8")
    print(f"built docs/index.html and docs/sw.js (cache buzz-{version}, {len(assets)} files)")


if __name__ == "__main__":
    main()
